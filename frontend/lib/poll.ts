/**
 * Класифікація помилок опитування статусу генерації.
 *
 * Окремий крихітний модуль БЕЗ залежностей навмисно: `lib/api.ts` тягне axios і
 * тому підвантажується динамічно (`await import("@/lib/api")`), а ці константи
 * потрібні в catch-гілці опитувача, куди динамічний імпорт уже не дістає.
 *
 * ⭐09.09.2026, з логів Caddy за тиждень: 377 відповідей 5xx, усі 502, і всі —
 * вікнами (03.09 22:00 — 151 штука, 06.09 16–17:00 — 155). Це рестарти бекенду
 * й інцидент OOM. Серед них 80 поспіль на `/api/status/<одна задача>`: людина
 * опитувала статус кожні 2.5 с, поки сервер лежав.
 *
 * Опитувач здавався після 4 невдач поспіль (~10 с) і писав «модель застаріла».
 * Але рестарт триває 15–25 с, а `/api/status` уміє ВІДНОВИТИ готову модель із
 * диска (`main.py`, гілка `disk_file` перед 404). Тобто ми оголошували втрату
 * там, де файл лежав готовий.
 *
 * Тому розрізняємо: 404 — задачі справді немає, здаємось одразу; 5xx або обрив
 * мережі — сервер піднімається, чекаємо до півтори хвилини.
 */

/** Тимчасова недоступність сервера, а не «задачі немає». */
export function isTransientStatusError(err: unknown): boolean {
  const status = (err as { response?: { status?: number } } | null)?.response?.status;
  if (typeof status !== "number") return true;   // обрив мережі / таймаут
  if (status === 404 || status === 410) return false;
  return status >= 500 || status === 429 || status === 408;
}

/** Невдач поспіль до здачі: задачі справді немає (~10 с). */
export const POLL_FAILS_GONE = 4;
/** Невдач поспіль до здачі: сервер піднімається (~90 с при кроці 2.5 с). */
export const POLL_FAILS_TRANSIENT = 36;
/** Після скількох невдач поспіль чесно сказати «зв'язок перервався». */
export const POLL_FAILS_NOTICE = 2;
